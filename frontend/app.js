function pushHistory(sensorData, risk, health) {
  const vibration = getSensorValue(sensorData, "vibration_rms_mm_s", "vibration_sensor");
  const temperature = getSensorValue(sensorData, "temperature_c", "temperature_sensor");
  telemetryHistory.vibration.push(vibration * 10);
  telemetryHistory.temperature.push(temperature);
  telemetryHistory.risk.push(risk);
  telemetryHistory.health.push(health);
  Object.keys(telemetryHistory).forEach(key => {
    if (Array.isArray(telemetryHistory[key])) telemetryHistory[key] = telemetryHistory[key].slice(-trendWindow);
  });
}

function renderSensors(sensorData) {
  const keys = Object.keys(sensorData).filter(key => numeric(sensorData[key]) !== null).slice(0, 8);
  document.getElementById("sensorGrid").innerHTML = keys.map(key => {
    const value = numeric(sensorData[key]);
    return `<div class="sensorTile"><small>${labelize(key)}</small><strong>${value.toFixed(2)}</strong></div>`;
  }).join("");
}

function renderRiskMatrix(data) {
  const signals = data.anomaly.signals || {};
  const cells = [
    ["Anomaly Score", data.anomaly.anomaly_score * 100, "%"],
    ["Bearing Wear", signals.bearing_wear || 0, "%"],
    ["Thermal Load", Math.min(100, ((signals.temperature || 0) / 90) * 100), "%"],
    ["Lubricant Loss", Math.max(0, 100 - (signals.lubricant_quality || 100)), "%"],
  ];
  document.getElementById("riskMatrix").innerHTML = cells.map(([label, value, suffix]) => {
    const safeValue = Math.max(0, Math.min(100, value));
    return `<div class="riskCell"><span>${label}</span><strong>${safeValue.toFixed(0)}${suffix}</strong><div class="miniBar"><div style="width:${safeValue}%"></div></div></div>`;
  }).join("");
  const analyticsMatrix = document.getElementById("analyticsRiskMatrix");
  if (analyticsMatrix) {
    analyticsMatrix.innerHTML = document.getElementById("riskMatrix").innerHTML;
  }
}

