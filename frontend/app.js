function applyAlert(level) {
  const cls = levelClass[level] || "info";
  const badge = document.getElementById("globalAlert");
  badge.className = `statusPill ${cls}`;
  badge.textContent = levelLabel[level] || "INFO - Stable";
  document.getElementById("topStatus").textContent = level === "GREEN" ? "Stable" : levelLabel[level].split("-")[1].trim();
  document.getElementById("decisionPriority").textContent = level === "GREEN" ? "INFO" : level;
  document.getElementById("notificationDot").style.background = cssVar(`--${cls}`);
}

function setUptime() {
  const seconds = Math.floor((Date.now() - telemetryHistory.startedAt) / 1000);
  const hh = String(Math.floor(seconds / 3600)).padStart(2, "0");
  const mm = String(Math.floor((seconds % 3600) / 60)).padStart(2, "0");
  const ss = String(seconds % 60).padStart(2, "0");
  document.getElementById("uptime").textContent = `${hh}:${mm}:${ss}`;
}

function switchView(viewName) {
  const selected = views[viewName] ? viewName : "dashboard";
  document.querySelectorAll("[data-view-panel]").forEach(panel => {
    panel.classList.toggle("activeView", panel.dataset.viewPanel === selected);
  });
  document.querySelectorAll(".sidebar a[data-view]").forEach(link => {
    link.classList.toggle("active", link.dataset.view === selected);
  });
  document.getElementById("viewEyebrow").textContent = views[selected].eyebrow;
  document.getElementById("viewTitle").textContent = views[selected].title;
  document.getElementById("viewDescription").textContent = views[selected].description;
  document.getElementById("sidebar").classList.remove("open");
  document.getElementById("overlay").classList.remove("open");
  requestAnimationFrame(() => redrawAll());
  window.setTimeout(redrawAll, 80);
}

function redrawAll() {
  drawHealth(telemetryHistory.health.at(-1) || 0, telemetryHistory.lastLevel);
  drawSensorHistory();
  drawMonitoringHistory();
  drawAnalyticsChart();
  if (lastData) {
    drawFutureTimeline(lastData.future.timeline);
    drawPredictionChart(lastData);
  }
}

function startRefreshTimer() {
  if (refreshTimer) clearInterval(refreshTimer);
  if (!isPaused) refreshTimer = setInterval(refresh, refreshMs);
}

async function refresh() {
  if (isPaused) return;
  const response = await fetch("/api/state");
  const data = await response.json();
  lastData = data;
  const health = data.prediction.health_percent;
  const risk = data.failure_probability * 100;
  const rul = data.prediction.rul_hours;

  pushHistory(data.sensor_data, risk, health);
  telemetryHistory.lastLevel = data.alert_level;
  applyAlert(data.alert_level);

  document.getElementById("sampleIndex").textContent = `Sample #${String(data.sample_index).padStart(3, "0")}`;
  document.getElementById("healthValue").textContent = `${health.toFixed(0)}%`;
  document.getElementById("healthDelta").textContent = data.prediction.model_name;
  document.getElementById("rulValue").textContent = `${rul.toFixed(1)} h`;
  document.getElementById("topRul").textContent = `${rul.toFixed(1)} h`;
  document.getElementById("topRisk").textContent = `${risk.toFixed(0)}%`;
  document.getElementById("riskValue").textContent = `${risk.toFixed(0)}%`;
  document.getElementById("riskMetric").textContent = `${risk.toFixed(0)}%`;
  document.getElementById("riskFill").style.width = `${Math.min(100, risk)}%`;
  document.getElementById("rulFill").style.width = `${Math.min(100, Math.max(0, health))}%`;
  document.getElementById("decisionText").textContent = data.decision.action;
  document.getElementById("decisionRationale").textContent = data.decision.rationale;
  document.getElementById("deathLine").textContent = `${data.future.estimated_death_timeline_hours} h to failure point`;

  renderSensors(data.sensor_data);
  renderSensorTable(data.sensor_data);
  renderRiskMatrix(data);
  renderLogs(data.logs);
  renderThoughts(data.thought_process);
  renderAlerts(data.alerts, data.alert);
  renderAlertsPage(data);
  renderDecisions(data);
  renderPredictionSummary(data);
  renderReportSummary(data);
  renderSettingsSummary(data);
  drawHealth(health, data.alert_level);
  drawSensorHistory();
  drawMonitoringHistory();
  drawAnalyticsChart();
  drawFutureTimeline(data.future.timeline);
  drawPredictionChart(data);
}

