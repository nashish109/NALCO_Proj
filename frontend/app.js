function numeric(value) {
  const number = Number(value);
  return Number.isFinite(number) ? number : null;
}

function labelize(key) {
  return key.replaceAll("_", " ").replace(/\b\w/g, char => char.toUpperCase());
}

function cssVar(name) {
  return getComputedStyle(document.documentElement).getPropertyValue(name).trim();
}

function getSensorValue(sensorData, ...keys) {
  for (const key of keys) {
    const value = numeric(sensorData[key]);
    if (value !== null) return value;
  }
  return 0;
}

function setupCanvas(canvas) {
  const rect = canvas.getBoundingClientRect();
  if (rect.width < 20 || rect.height < 20) return null;
  const ratio = window.devicePixelRatio || 1;
  canvas.width = Math.max(1, Math.floor(rect.width * ratio));
  canvas.height = Math.max(1, Math.floor(rect.height * ratio));
  const ctx = canvas.getContext("2d");
  ctx.setTransform(ratio, 0, 0, ratio, 0, 0);
  return { ctx, width: rect.width, height: rect.height };
}

function drawHealth(value, level) {
  const canvas = document.getElementById("healthCanvas");
  const canvasSetup = setupCanvas(canvas);
  if (!canvasSetup) return;
  const { ctx, width, height } = canvasSetup;
  const centerX = width / 2;
  const centerY = height / 2;
  const radius = Math.min(width, height) / 2 - 10;
  const start = Math.PI * 0.78;
  const end = Math.PI * 2.22;
  const percentEnd = start + (end - start) * (Math.max(0, Math.min(100, value)) / 100);
  const color = cssVar(`--${levelClass[level] || "healthy"}`);

  ctx.clearRect(0, 0, width, height);
  ctx.lineCap = "round";
  ctx.lineWidth = 12;
  ctx.strokeStyle = "#263645";
  ctx.beginPath();
  ctx.arc(centerX, centerY, radius, start, end);
  ctx.stroke();

  ctx.strokeStyle = color;
  ctx.beginPath();
  ctx.arc(centerX, centerY, radius, start, percentEnd);
  ctx.stroke();

  ctx.lineWidth = 1;
  ctx.strokeStyle = "rgba(183,196,207,0.28)";
  for (let i = 0; i <= 10; i += 1) {
    const angle = start + ((end - start) / 10) * i;
    const inner = radius - 18;
    const outer = radius - 8;
    ctx.beginPath();
    ctx.moveTo(centerX + Math.cos(angle) * inner, centerY + Math.sin(angle) * inner);
    ctx.lineTo(centerX + Math.cos(angle) * outer, centerY + Math.sin(angle) * outer);
    ctx.stroke();
  }
}

function drawLineChart(canvasId, series, options) {
  const canvas = document.getElementById(canvasId);
  if (!canvas) return;
  const canvasSetup = setupCanvas(canvas);
  if (!canvasSetup) return;
  const { ctx, width, height } = canvasSetup;
  const padding = { left: 42, right: 18, top: 18, bottom: 30 };
  const plotW = width - padding.left - padding.right;
  const plotH = height - padding.top - padding.bottom;
  const normalizedSeries = series.map(item => ({
    ...item,
    values: normalizeSeries(item.values, options.points),
  }));
  const allValues = normalizedSeries.flatMap(item => item.values);
  const min = options.min ?? Math.min(...allValues, 0);
  const max = options.max ?? Math.max(...allValues, 1);
  const scaleY = value => padding.top + plotH - ((value - min) / Math.max(1, max - min)) * plotH;
  const scaleX = index => padding.left + (index / Math.max(1, options.points - 1)) * plotW;

  ctx.clearRect(0, 0, width, height);
  ctx.strokeStyle = "rgba(148,163,184,0.16)";
  ctx.lineWidth = 1;
  ctx.fillStyle = cssVar("--muted");
  ctx.font = "12px Inter, system-ui";

  for (let i = 0; i <= 4; i += 1) {
    const y = padding.top + (plotH / 4) * i;
    ctx.beginPath();
    ctx.moveTo(padding.left, y);
    ctx.lineTo(width - padding.right, y);
    ctx.stroke();
  }

  ctx.fillText(String(Math.round(max)), 6, padding.top + 4);
  ctx.fillText(String(Math.round(min)), 6, padding.top + plotH);

  normalizedSeries.forEach(item => {
    ctx.strokeStyle = item.color;
    ctx.lineWidth = 2;
    ctx.beginPath();
    item.values.forEach((value, index) => {
      const x = scaleX(index);
      const y = scaleY(value);
      if (index === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    });
    ctx.stroke();
    item.values.forEach((value, index) => {
      const x = scaleX(index);
      const y = scaleY(value);
      ctx.fillStyle = item.color;
      ctx.beginPath();
      ctx.arc(x, y, item.values.length <= 8 ? 3.2 : 2.2, 0, Math.PI * 2);
      ctx.fill();
    });
  });

  let legendX = padding.left;
  normalizedSeries.forEach(item => {
    ctx.fillStyle = item.color;
    ctx.fillRect(legendX, height - 16, 10, 3);
    ctx.fillStyle = cssVar("--text-soft");
    ctx.fillText(item.label, legendX + 15, height - 11);
    legendX += 118;
  });
}

function normalizeSeries(values, points) {
  const clean = values.filter(value => Number.isFinite(value));
  if (clean.length === 0) return Array.from({ length: points }, () => 0);
  if (clean.length >= points) return clean.slice(-points);
  const first = clean[0];
  const prefix = Array.from({ length: points - clean.length }, (_, index) => {
    const wave = Math.sin(index * 0.7) * Math.max(0.8, Math.abs(first) * 0.015);
    return Math.max(0, first + wave);
  });
  return [...prefix, ...clean];
}

function drawFutureTimeline(points) {
  const normalized = points.map(point => ({
    ...point,
    risk_percent: point.failure_probability * 100,
  }));
  drawLineChart("timelineCanvas", [
    { label: "Health", color: cssVar("--accent"), values: normalized.map(point => point.health_percent) },
    { label: "Failure risk", color: cssVar("--critical"), values: normalized.map(point => point.risk_percent) },
  ], { min: 0, max: 100, points: normalized.length });
}

